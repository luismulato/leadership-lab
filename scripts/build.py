#!/usr/bin/env python3 -I
"""Assemble build/<env>/ : the single Cloudflare Pages project for one environment.

  python3 -I scripts/build.py --env dev [--out DIR] [--set key=value ...]

--out DIR builds there instead of build/<env> (the tests use it: build/<env> may be served by a running dev server).

Layout produced:
  build/<env>/public/             shell at "/" and every app under "/<id>/"  (+ env.js with the environment name)
  build/<env>/functions/          shell functions + one API per app under "/<id>/api"
  build/<env>/db/migrations/      the single D1 schema
  build/<env>/wrangler.toml       generated for the environment (ONE D1, ONE KV)

The application code is identical in every environment: only env.js and wrangler.toml differ.
--set overrides a config value for this build only (not persisted), e.g. --set target=cloudflare, --set feedback_form_url= (empty = no feedback button)
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import config  # noqa: E402

SKIP = shutil.ignore_patterns(".DS_Store", ".wrangler", "node_modules", ".dev*", "activo.json", "tests")


def register_installed_themes(temas_dir):
    """Write temas/instalados.json in the BUILD from every temas/<id>/tema.json not listed in the versioned index.json.
    A theme delivered as a .zip (not in git) is therefore registered just by being unzipped before `make dev|deploy`."""
    listed = {t["id"] for t in json.loads((temas_dir / "index.json").read_text())}
    found = []
    for d in sorted(temas_dir.iterdir()):
        meta = d / "tema.json"
        if d.is_dir() and d.name not in listed and re.fullmatch(r"[a-z0-9-]+", d.name) and meta.is_file():
            found.append({"id": d.name, "nombre": json.loads(meta.read_text()).get("nombre") or d.name})
    (temas_dir / "instalados.json").write_text(json.dumps(found, ensure_ascii=False, indent=2) + "\n")


def build_apps_with_generators(apps):
    """Some apps generate their public/index.html from sources (build.py in the app folder)."""
    for app in apps:
        script = ROOT / "apps" / app / "build.py"
        if script.exists():
            subprocess.run([sys.executable, "-I", "build.py"], cwd=script.parent, check=True, stdout=subprocess.DEVNULL)


def wrangler_toml(cfg, env_cfg, local):
    cf = env_cfg["cloudflare"]
    db_id = f"local-{cf['d1_database']}" if local else (cf["d1_id"] or "SET-BY-CLOUDFLARE-BOOTSTRAP")
    kv_id = f"local-{cf['pages_project']}-skin" if local else (cf["kv_id"] or "SET-BY-CLOUDFLARE-BOOTSTRAP")
    return f"""# GENERATED by scripts/build.py - do not edit (edit config/environments.json).
name = "{cf['pages_project']}"
pages_build_output_dir = "public"
compatibility_date = "{cfg['compatibility_date']}"

# ONE D1 database shared by every app of the site.
[[d1_databases]]
binding = "DB"
database_name = "{cf['d1_database']}"
database_id = "{db_id}"
migrations_dir = "db/migrations"

# Shell KV: active theme.
[[kv_namespaces]]
binding = "SKIN"
id = "{kv_id}"

# Secret (not stored here): APP_ADMIN_CLAVE
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", required=True)
    ap.add_argument("--out", default="", help="output directory (default: build/<env>)")
    ap.add_argument("--set", action="append", default=[], metavar="key=value")
    args = ap.parse_args()

    cfg = config.load()
    if args.env not in cfg["environments"]:
        sys.exit(f"unknown environment: {args.env} (known: {', '.join(cfg['environments'])})")
    env_cfg = json.loads(json.dumps(cfg["environments"][args.env]))
    for item in args.set:
        key, _, value = item.partition("=")
        env_cfg[key] = value
    local = env_cfg["target"] == "local"

    apps = config.app_ids()
    build_apps_with_generators(apps)

    out = pathlib.Path(args.out).resolve() if args.out else ROOT / "build" / args.env
    if out.exists():
        shutil.rmtree(out)
    pub, fn = out / "public", out / "functions"
    pub.mkdir(parents=True)
    fn.mkdir()

    shell = ROOT / "apps" / "shell"
    shutil.copy2(shell / "index.html", pub / "index.html")
    for part in ("assets", "skin", "app-admin"):
        shutil.copytree(shell / part, pub / part, ignore=SKIP)
    register_installed_themes(pub / "skin" / "temas")
    shutil.copytree(shell / "functions", fn, dirs_exist_ok=True, ignore=SKIP)

    for app in apps:
        src = ROOT / "apps" / app
        shutil.copytree(src / "public", pub / app, ignore=SKIP)
        if (src / "functions").exists():
            shutil.copytree(src / "functions", fn / app, ignore=SKIP)

    shutil.copytree(ROOT / "db" / "migrations", out / "db" / "migrations")
    (out / "wrangler.toml").write_text(wrangler_toml(cfg, env_cfg, local), encoding="utf8")
    env_js = {"name": args.env, "feedbackFormUrl": env_cfg.get("feedback_form_url", "")}
    (pub / "env.js").write_text("/* GENERATED by scripts/build.py */\nwindow.LL_ENV = " + json.dumps(env_js) + ";\n", encoding="utf8")
    print(f"{out.relative_to(ROOT) if out.is_relative_to(ROOT) else out} ready: shell + {', '.join(apps)}")


if __name__ == "__main__":
    main()
